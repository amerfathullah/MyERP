    [Fact]
    public void Dunning_interest_calculation_daily_simple_interest()
    {
        // Per ERPNext: interest = rate / 100 / 365 × overdue_days × outstanding (per invoice)
        var overdueInvoices = new List<(decimal outstanding, int overdueDays)>
        {
            (1000m, 30),
            (2000m, 60),
        };
        var interest = DunningManager.CalculateInterest(10m, overdueInvoices);

        // Expected: (10/100/365) × (30×1000 + 60×2000) = 0.00027397 × 150000 ≈ 41.096
        Assert.True(interest > 41m && interest < 42m);
    }

    [Fact]
    public void Dunning_interest_zero_when_rate_is_zero()
    {
        var overdueInvoices = new List<(decimal outstanding, int overdueDays)> { (5000m, 90) };
        var interest = DunningManager.CalculateInterest(0m, overdueInvoices);
        Assert.Equal(0m, interest);
    }

    [Fact]
    public void Dunning_interest_zero_when_no_invoices()
    {
        var interest = DunningManager.CalculateInterest(12m, new List<(decimal, int)>());
        Assert.Equal(0m, interest);
    }

    [Fact]
    public void Dunning_level_sequential_from_one()
    {
        // Per ERPNext: level = count of existing submitted dunnings + 1
        // First dunning for a customer should be level 1
        var dunning = new Dunning(Guid.NewGuid(), Guid.NewGuid(), Guid.NewGuid(),
            DateTime.UtcNow.Date, 1);
        Assert.Equal(1, dunning.DunningLevel);
    }

    [Fact]
    public void Dunning_grand_total_includes_outstanding_fee_interest()
    {
        var dunning = new Dunning(Guid.NewGuid(), Guid.NewGuid(), Guid.NewGuid(),
            DateTime.UtcNow.Date, 2)
        {
            DunningFee = 50m,
            InterestAmount = 25.50m,
        };
        dunning.AddOverduePayment(Guid.NewGuid(), 1000m, DateTime.UtcNow.AddDays(-30), 30);
        dunning.AddOverduePayment(Guid.NewGuid(), 500m, DateTime.UtcNow.AddDays(-15), 15);

        Assert.Equal(1500m, dunning.TotalOutstanding);
        Assert.Equal(1500m + 50m + 25.50m, dunning.GrandTotal);
    }

